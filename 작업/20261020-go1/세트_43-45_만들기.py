def verse(ls, extra=()):
    out, prev = "", None
    for y, t in ls:
        if prev is not None:
            out += "\n\n" if y - prev > 25 else "\n"
        out += t.strip()
        prev = y
    for _, t in extra:
        out += "\n" + t.strip()
    return out


