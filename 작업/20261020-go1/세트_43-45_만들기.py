def nth_of(text, s, anchor):
    """anchor(원문 일부) 안에서 시작하는 s 가 text 전체에서 몇 번째인지."""
    assert text.count(anchor) == 1, anchor
    pos = text.index(anchor) + anchor.index(s)
    n, i = 0, text.find(s)
    while i != -1 and i <= pos:
        n += 1
        i = text.find(s, i + 1)
    return n


def bolds(text, spec):
    out = []
    for item in spec:
        s, anchor = item if isinstance(item, tuple) else (item, item)
        n = nth_of(text, s, anchor)
        out.append(s if text.count(s) == 1 else {"text": s, "nth": n})
    return out


