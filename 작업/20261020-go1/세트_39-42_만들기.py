def lines(pi, col, y0, y1):
    p = doc[pi]
    out = []
    for b in p.get_text("dict")["blocks"]:
        for l in b.get("lines", []):
            x, y = l["bbox"][0], l["bbox"][1]
            if (0 if x < p.rect.width / 2 - 5 else 1) == col and y0 <= y <= y1:
                out.append((y, x, "".join(s["text"] for s in l["spans"])))
    return [(x, t) for _, x, t in sorted(out)]


