def verse(lines, stanza_sizes):
    assert sum(stanza_sizes) == len(lines), (sum(stanza_sizes), len(lines))
    out, k = [], 0
    for n in stanza_sizes:
        out.append("\n".join(lines[k: k + n]))
        k += n
    return "\n\n".join(out)


