def nth_of(text, s, anchor):
    """anchor(원문 일부) 안에서 시작하는 s 가 text 전체에서 몇 번째인지."""
    pos = text.index(anchor) + anchor.index(s)
    n, i = 0, text.find(s)
    while i != -1 and i <= pos:
        n += 1
        i = text.find(s, i + 1)
    return n


