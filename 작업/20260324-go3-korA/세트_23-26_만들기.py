def nth_at(text, phrase, line_start):
    """phrase 가 line_start 로 시작하는 줄 안에서 처음 나오는 자리가 text 에서 몇 번째 phrase 인지."""
    li = text.index(line_start)
    pos = text.index(phrase, li)
    n = 0
    i = -1
    while True:
        i = text.find(phrase, i + 1)
        n += 1
        if i == pos:
            return n
        assert i >= 0 and i < pos, (phrase, line_start)


