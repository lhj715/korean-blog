import re


def fq(fid, q):
    """그림 pdf_text 안의  때문에 글자 그대로 못 찾는 인용을, 그림 글자에서 그대로 오려 낸다."""
    src = next(p for p in d["passage"] if p["id"] == fid)["pdf_text"]
    pat = r"[\s]*".join(re.escape(c) for c in q if not c.isspace())
    m = re.search(pat, src)
    assert m, (fid, q)
    return m.group(0)


def J(choice, verdict, ans, ev, reason, xq=None):
    j = {"choice": choice, "verdict": verdict, "is_answer": ans, "reason": reason,
         "evidence": [({"source": s, "fig": p, "quote": fq(p, q)} if s == "figure" else {"source": s, "para": p, "quote": q}) for s, p, q in ev]}
    if xq:
        j.update({"basis": "해설지", "explanation_quote": xq})
    else:
        j.update({"basis": "자체"})
    return j


