def between(s, a, b, incl_b=True):
    i = s.index(a)
    j = s.index(b, i) + (len(b) if incl_b else 0)
    return s[i:j]


def split_dialogue(text, speakers):
    """'선생님: …학생: …' 처럼 이어 붙은 대화를 말한 이마다 나눈다."""
    pat = "(" + "|".join(re.escape(s) for s in speakers) + r")\s*:"
    idx = [m.start() for m in re.finditer(pat, text)]
    return [text[a:b] for a, b in zip(idx, idx[1:] + [len(text)])]


