def fq(fid, q):
    """그림 글자에서 공백 차이를 무시하고 인용을 오려 낸다."""
    src = next(p for p in d["passage"] if p["id"] == fid)
    src = (src["pdf_text"] + " " + src["raster_text"]).strip()
    pat = r"[\s]*".join(re.escape(c) for c in q if not c.isspace())
    m = re.search(pat, src)
    assert m, (fid, q)
    return m.group(0)


