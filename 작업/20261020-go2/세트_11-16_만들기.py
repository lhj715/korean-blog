def X(no, a, b):
    sec = section(no)
    keep = [(i, c) for i, c in enumerate(sec) if not c.isspace()]
    comp = "".join(c for _, c in keep)
    ca = re.sub(r"\s+", "", a)
    cb = re.sub(r"\s+", "", b)
    ia = comp.index(ca)
    ib = comp.index(cb, ia) + len(cb)
    out = sec[keep[ia][0]: keep[ib - 1][0] + 1].replace("\n", "")
    assert "===" not in out, out
    return out


