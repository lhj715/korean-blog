def fix(t):
    t = t.strip().replace("\u3000", " ")
    parts = t.split("\uf000")
    if len(parts) > 1:
        out = parts[0]
        for k, s in enumerate(parts[1:]):
            out += ("『" if k % 2 == 0 else "』") + s
        t = out
    return t


