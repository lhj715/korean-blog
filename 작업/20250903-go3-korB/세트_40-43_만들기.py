def sq(s):
    return re.sub(r"[\s\u200b]+", "", s)


def E(start, end):
    pat = lambda s: r"\s*".join(re.escape(c) for c in sq(s))
    ms = list(re.finditer(pat(start) + r".*?" + pat(end), ORIG, re.S))
    assert len(ms) == 1, (start, len(ms))
    return ms[0].group(0)


def J(choice, verdict, ans, ev, reason, xq):
    out = {"choice": choice, "verdict": verdict, "is_answer": ans, "basis": "해설지", "reason": reason, "evidence": []}
