def verse(lines, sizes):
    assert sum(sizes) == len(lines), (sum(sizes), len(lines))
    out, k = [], 0
    for n in sizes:
        out.append("\n".join(lines[k:k + n]))
        k += n
    return "\n\n".join(out)


