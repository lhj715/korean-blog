def para_split(lines, starts):
    out, cur = [], None
    for l in lines:
        if any(l.startswith(s) for s in starts):
            if cur is not None:
                out.append(cur)
            cur = [l]
        else:
            cur.append(l)
    out.append(cur)
    return ["".join(c).strip().replace("\uf000주역\uf000", "『주역』") for c in out]


